"""Splice generated tables (report_tables.py output) into README.md between the RESULTS markers.
usage: update_readme.py tables.md"""
import os  # added by the repo export (paths are env/config driven)
import sys
D = os.path.join(os.environ.get('TRANSCRIPTLAB_ROOT', '.'), 'experiments/contagion')
B, E = '<!-- RESULTS:BEGIN (generated by scripts/report_tables.py; do not edit by hand) -->', '<!-- RESULTS:END -->'
t = open(sys.argv[1]).read().strip()
r = open(f'{D}/README.md').read()
block = f'{B}\n\n{t}\n\n{E}'
if B in r and E in r:
    r = r[:r.index(B)] + block + r[r.index(E) + len(E):]
else:
    anchor = '## Caveats and threats to validity'
    r = r.replace(anchor, '## Results (generated)\n\n' + block + '\n\n' + anchor, 1) if anchor in r else r + '\n\n## Results (generated)\n\n' + block + '\n'
open(f'{D}/README.md', 'w').write(r)
print('README updated;', len(t), 'chars of tables')
